"""Write ai-playground/backgrounds.js with every image in ai-playground/backgrounds/.

The site is static, so the browser cannot list a folder by itself; the playground
reads this generated list and picks a random background on each load.
Run after adding or removing a background: python3 scripts/list_backgrounds.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FOLDER = ROOT / "ai-playground" / "backgrounds"
OUTPUT = ROOT / "ai-playground" / "backgrounds.js"
EXTENSIONS = {".jpg", ".jpeg", ".png", ".webp", ".avif", ".gif"}

files = (
    sorted(
        f"backgrounds/{path.name}"
        for path in FOLDER.iterdir()
        if path.is_file() and path.suffix.lower() in EXTENSIONS
    )
    if FOLDER.is_dir()
    else []
)

OUTPUT.write_text(
    "// Generated by scripts/list_backgrounds.py - do not edit by hand.\n"
    f"window.playgroundBackgrounds = {json.dumps(files, indent=2)};\n",
    encoding="utf-8",
)
print(f"{len(files)} background(s) written to {OUTPUT.relative_to(ROOT)}")
